/**
 * Professional Export Utilities for CSV and PDF generation
 * Includes letterhead, branding, and professional formatting
 */

import { logger } from './monitoring';

export interface ExportData {
  headers: string[];
  rows: (string | number)[][];
}

export interface ReportConfig {
  title: string;
  subtitle?: string;
  generatedBy?: string;
  dateRange?: { start: string; end: string };
  filters?: Record<string, string>;
  language?: 'en' | 'fr';
}

// Company branding info
const COMPANY_INFO = {
  name: 'RiadPrix',
  tagline: 'Revenue Intelligence for Moroccan Hospitality',
  website: 'www.riadprix.com',
  email: 'reports@riadprix.com',
};

// Format date for reports
function formatReportDate(date: Date, language: 'en' | 'fr' = 'en'): string {
  const options: Intl.DateTimeFormatOptions = {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  };
  return date.toLocaleDateString(language === 'fr' ? 'fr-FR' : 'en-US', options);
}

// Generate unique report ID
function generateReportId(): string {
  const timestamp = Date.now().toString(36).toUpperCase();
  const random = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `RPX-${timestamp}-${random}`;
}

// Professional CSV Export with metadata header
export function exportToCSV(
  data: ExportData,
  filename: string = 'export.csv',
  config?: ReportConfig
) {
  try {
    const reportId = generateReportId();
    const generatedAt = formatReportDate(new Date(), config?.language);
    const lang = config?.language || 'en';
    
    // Build metadata header section
    const metadataLines: string[] = [];
    metadataLines.push(`"${COMPANY_INFO.name} - ${lang === 'fr' ? 'Rapport Exporté' : 'Exported Report'}"`);
    metadataLines.push(`"${config?.title || (lang === 'fr' ? 'Rapport de Données' : 'Data Report')}"`);
    if (config?.subtitle) {
      metadataLines.push(`"${config.subtitle}"`);
    }
    metadataLines.push('""'); // Empty line
    metadataLines.push(`"${lang === 'fr' ? 'ID du Rapport' : 'Report ID'}","${reportId}"`);
    metadataLines.push(`"${lang === 'fr' ? 'Généré le' : 'Generated On'}","${generatedAt}"`);
    if (config?.generatedBy) {
      metadataLines.push(`"${lang === 'fr' ? 'Généré par' : 'Generated By'}","${config.generatedBy}"`);
    }
    if (config?.dateRange) {
      metadataLines.push(`"${lang === 'fr' ? 'Période' : 'Date Range'}","${config.dateRange.start} - ${config.dateRange.end}"`);
    }
    if (config?.filters) {
      Object.entries(config.filters).forEach(([key, value]) => {
        metadataLines.push(`"${key}","${value}"`);
      });
    }
    metadataLines.push('""'); // Empty line separator
    metadataLines.push(`"=== ${lang === 'fr' ? 'DÉBUT DES DONNÉES' : 'DATA SECTION START'} ==="`);
    metadataLines.push('""');

    // Build data section
    const dataLines: string[] = [];
    dataLines.push(data.headers.map(h => `"${String(h).replace(/"/g, '""')}"`).join(','));
    data.rows.forEach(row => {
      dataLines.push(row.map(cell => `"${String(cell).replace(/"/g, '""')}"`).join(','));
    });

    // Build footer section
    const footerLines: string[] = [];
    footerLines.push('""');
    footerLines.push(`"=== ${lang === 'fr' ? 'FIN DES DONNÉES' : 'DATA SECTION END'} ==="`);
    footerLines.push('""');
    footerLines.push(`"${lang === 'fr' ? 'Total des enregistrements' : 'Total Records'}","${data.rows.length}"`);
    footerLines.push('""');
    footerLines.push(`"${lang === 'fr' ? 'Avertissement' : 'Disclaimer'}","${lang === 'fr' ? 'Ces données sont fournies à titre informatif uniquement. RiadPrix ne garantit pas l\'exactitude des estimations de marché.' : 'This data is provided for informational purposes only. RiadPrix does not guarantee the accuracy of market estimates.'}"`);
    footerLines.push(`"${lang === 'fr' ? 'Contact' : 'Contact'}","${COMPANY_INFO.email}"`);
    footerLines.push(`"${lang === 'fr' ? 'Site Web' : 'Website'}","${COMPANY_INFO.website}"`);
    footerLines.push('""');
    footerLines.push(`"© ${new Date().getFullYear()} ${COMPANY_INFO.name}. ${lang === 'fr' ? 'Tous droits réservés.' : 'All rights reserved.'}"`);

    // Combine all sections
    const csvContent = [...metadataLines, ...dataLines, ...footerLines].join('\n');

    // Add BOM for Excel UTF-8 compatibility
    const BOM = '\uFEFF';
    const blob = new Blob([BOM + csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);

    link.setAttribute('href', url);
    link.setAttribute('download', filename);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    URL.revokeObjectURL(url);
    logger.info('CSV export completed', { filename, reportId });
    return reportId;
  } catch (error) {
    logger.error('CSV export failed', error as Error);
    throw error;
  }
}

