// Helper to format benchmark data for export
export function formatBenchmarkDataForExport(benchmarks: Array<{
  property_type: string;
  min_price: number | null;
  median_price: number | null;
  max_price: number | null;
  period_start: string;
  period_end: string;
}>): ExportData {
  return {
    headers: ['Property Type', 'Min Price (MAD)', 'Median Price (MAD)', 'Max Price (MAD)', 'Period Start', 'Period End'],
    rows: benchmarks.map(b => [
      b.property_type,
      b.min_price || 0,
      b.median_price || 0,
      b.max_price || 0,
      b.period_start,
      b.period_end,
    ]),
  };
}

// Format market data for export
export function formatMarketDataForExport(
  marketData: Array<{
    date: string;
    avg_price: number | null;
    occupancy_rate: number | null;
    property_type: string;
  }>,
  language: 'en' | 'fr' = 'en'
): ExportData {
  const headers = language === 'fr'
    ? ['Date', 'Prix Moyen (MAD)', 'Taux d\'Occupation (%)', 'Type de Propriété']
    : ['Date', 'Average Price (MAD)', 'Occupancy Rate (%)', 'Property Type'];

  return {
    headers,
    rows: marketData.map(d => [
      d.date,
      d.avg_price || 0,
      d.occupancy_rate ? `${d.occupancy_rate}%` : 'N/A',
      d.property_type,
    ]),
  };
}

// Format property data for export
export function formatPropertyDataForExport(
  properties: Array<{
    name: string;
    property_type: string;
    current_price: number | null;
    bedrooms: number | null;
    bathrooms: number | null;
    max_guests: number | null;
  }>,
  language: 'en' | 'fr' = 'en'
): ExportData {
  const headers = language === 'fr'
    ? ['Nom', 'Type', 'Prix Actuel (MAD)', 'Chambres', 'Salles de Bain', 'Capacité Max']
    : ['Name', 'Type', 'Current Price (MAD)', 'Bedrooms', 'Bathrooms', 'Max Guests'];

  return {
    headers,
    rows: properties.map(p => [
      p.name,
      p.property_type,
      p.current_price || 'N/A',
      p.bedrooms || 'N/A',
      p.bathrooms || 'N/A',
      p.max_guests || 'N/A',
    ]),
  };
}

// Format recommendations for export
export function formatRecommendationsForExport(
  recommendations: Array<{
    property_name: string;
    current_price: number;
    recommended_price: number;
    confidence_score: number | null;
    valid_from: string;
    valid_to: string;
    reasoning: string | null;
  }>,
  language: 'en' | 'fr' = 'en'
): ExportData {
  const headers = language === 'fr'
    ? ['Propriété', 'Prix Actuel (MAD)', 'Prix Recommandé (MAD)', 'Variation (%)', 'Confiance', 'Valide Du', 'Valide Au', 'Raisonnement']
    : ['Property', 'Current Price (MAD)', 'Recommended Price (MAD)', 'Change (%)', 'Confidence', 'Valid From', 'Valid To', 'Reasoning'];

  return {
    headers,
    rows: recommendations.map(r => {
      const change = ((r.recommended_price - r.current_price) / r.current_price * 100).toFixed(1);
      return [
        r.property_name,
        r.current_price,
        r.recommended_price,
        `${change}%`,
        r.confidence_score ? `${(r.confidence_score * 100).toFixed(0)}%` : 'N/A',
        r.valid_from,
        r.valid_to,
        r.reasoning || 'N/A',
      ];
    }),
  };
}
